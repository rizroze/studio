#!/usr/bin/env node
// Experiments content pipeline.
//
// Workflow: drop images (webp / jpg / png / heic) into
// public/content/experiments/, then run `npm run experiments`.
//
// For each source image this:
//   1. converts it to a canonical .webp (if it isn't one already),
//   2. generates a 640px .med.jpg (grid) and 240px .thumb.jpg (preview),
//   3. reads its pixel dimensions,
// then rewrites src/v2/experiments.ts with the full gallery + dims, ordered
// newest-first (by file mtime). Everything is done with `sips` (macOS built-in
// — same tool the rest of the site's dims were made with), no npm deps.

import { readdirSync, statSync, existsSync, writeFileSync } from 'node:fs'
import { join, dirname, extname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'public', 'content', 'experiments')
const outFile = join(root, 'src', 'v2', 'experiments.ts')

// Pin these to the front of the gallery (matched by base-name substring), in
// this order, regardless of date. Everything else follows newest-first.
const FEATURED = ['Frame 2085660679'] // world. cover — hero of the bento

const sips = (...args) => execFileSync('sips', args, { stdio: ['ignore', 'pipe', 'pipe'] }).toString()
// sips on macOS can READ webp but not WRITE it — use cwebp for the conversion.
const toWebp = (src, out) => execFileSync('cwebp', ['-q', '82', src, '-o', out], { stdio: ['ignore', 'ignore', 'pipe'] })

// source images we know how to process (exclude the generated variants)
const isVariant = (f) => /\.(med|thumb)\.jpg$/i.test(f)
const isSource = (f) => /\.(webp|png|jpe?g|heic)$/i.test(f) && !isVariant(f)

function dims(file) {
  const out = sips('-g', 'pixelWidth', '-g', 'pixelHeight', file)
  const w = +(out.match(/pixelWidth:\s*(\d+)/)?.[1] ?? 0)
  const h = +(out.match(/pixelHeight:\s*(\d+)/)?.[1] ?? 0)
  return [w, h]
}

if (!existsSync(dir)) {
  console.error(`experiments: ${dir} does not exist`)
  process.exit(1)
}

// collect unique base names (a piece may already have a .webp + a source jpg)
const files = readdirSync(dir).filter(isSource)
const bases = new Map() // baseName -> { orig, sortKey }
for (const f of files) {
  const base = basename(f, extname(f))
  const ext = extname(f).toLowerCase()
  const full = join(dir, f)
  const mtime = statSync(full).mtimeMs
  const rec = bases.get(base) ?? { orig: null, sortKey: 0 }
  // Ordering = created date, newest first. The ORIGINAL dropped file (png/jpg/
  // heic) carries the real timestamp; the .webp we generate has a meaningless
  // "just now" mtime, so it must never drive the sort. An original always wins
  // as the timing signal; a lone .webp (dropped directly) is the fallback.
  if (ext === '.webp') { if (!rec.orig) rec.sortKey = mtime }
  else { rec.orig = full; rec.sortKey = mtime }
  bases.set(base, rec)
}

const gallery = []
const dimMap = {}

// newest first
const ordered = [...bases.entries()].sort((a, b) => b[1].sortKey - a[1].sortKey)

// then pull FEATURED pieces to the front, in listed order; the rest stay
// newest-first (Node's sort is stable, so date order is preserved for ties)
const rank = (base) => {
  const i = FEATURED.findIndex((f) => base.includes(f))
  return i === -1 ? Infinity : i
}
ordered.sort((a, b) => rank(a[0]) - rank(b[0]))

for (const [base, { orig }] of ordered) {
  const webp = join(dir, `${base}.webp`)
  // 1. canonical webp — convert from the original if we haven't already
  if (!existsSync(webp)) {
    toWebp(orig, webp)
    console.log(`  converted → ${base}.webp`)
  }
  // 2. variants
  const med = join(dir, `${base}.med.jpg`)
  const thumb = join(dir, `${base}.thumb.jpg`)
  sips('-Z', '640', '-s', 'format', 'jpeg', webp, '--out', med)
  sips('-Z', '240', '-s', 'format', 'jpeg', webp, '--out', thumb)
  // 3. dims
  const ref = `/content/experiments/${base}.webp`
  dimMap[ref] = dims(webp)
  gallery.push(ref)
}

const body = `// AUTO-GENERATED by scripts/gen-experiments.mjs — do not edit by hand.
// Drop images in public/content/experiments/ then run \`npm run experiments\`.

export const EXPERIMENTS_GALLERY: string[] = [
${gallery.map((s) => `  '${s}',`).join('\n')}
]

export const EXPERIMENTS_DIMS: Record<string, [number, number]> = {
${gallery.map((s) => `  '${s}': [${dimMap[s][0]}, ${dimMap[s][1]}],`).join('\n')}
}
`

writeFileSync(outFile, body)
console.log(`experiments: ${gallery.length} image(s) → src/v2/experiments.ts`)
